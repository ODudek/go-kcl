// Package utils
package utils

import (
	"crypto/rand"
	"fmt"
)

// MustNewUUID generates a random (version 4) UUID and panics if failed.
// It is the default worker ID; unlike the version 1 UUID it replaced, it does
// not carry the host's MAC address.
func MustNewUUID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(err)
	}
	b[6] = b[6]&0x0f | 0x40 // version 4
	b[8] = b[8]&0x3f | 0x80 // RFC 4122 variant

	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}
